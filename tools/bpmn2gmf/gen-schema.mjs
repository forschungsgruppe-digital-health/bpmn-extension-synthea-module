#!/usr/bin/env node
// Generates a JSON Schema for a Synthea module (the JSON the converter writes) FROM
// `required-fields.mjs`, so the required fields exist in one place only.
//
// What the schema says: the shape of a module, the type of every state, the fields each type needs
// (the same rule as `missingFields`), and exactly one transition per state (none on Terminal).
// What it cannot say, and `verify.mjs` / `verify-flow.mjs` keep: that a transition target exists,
// that a state is reachable from Initial, that probabilities sum to 1, the order of states.
// Kramer et al. 2025 call Synthea JSON unsuitable for schemas; that is true of those cross-state
// rules, not of the per-state fields.
//
// Usage:
//   node tools/bpmn2gmf/gen-schema.mjs           write tools/bpmn2gmf/module.schema.json
//   node tools/bpmn2gmf/gen-schema.mjs --check   exit 1 if the stored schema is stale (drift guard)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { REQUIRED_FIELDS } from './required-fields.mjs';

export const SCHEMA_PATH = fileURLToPath(new URL('./module.schema.json', import.meta.url));

// State types that need no field of their own (Encounter has a rule of its own below).
const OTHER_TYPES = ['Initial', 'Terminal', 'Simple', 'Death', 'Encounter', 'EncounterEnd', 'Physiology'];

// Required fields that hold a list: an empty list counts as missing, as in missingFields.
const LISTS = ['codes', 'supplies', 'observations', 'series'];

const TRANSITIONS = [
  'direct_transition', 'distributed_transition', 'conditional_transition', 'complex_transition', 'lookup_table_transition'
];

const needs = (list) => {
  const plain = list.filter((f) => !Array.isArray(f));
  const groups = list.filter(Array.isArray);
  const out = {};
  if (plain.length) out.required = plain;
  const lists = plain.filter((f) => LISTS.includes(f));
  if (lists.length) out.properties = Object.fromEntries(lists.map((f) => [f, { type: 'array', minItems: 1 }]));
  if (groups.length) {
    // "one of": at least one of the fields is present (missingFields uses `some`)
    out.allOf = groups.map((g) => ({ anyOf: g.map((f) => ({ required: [f] })) }));
  }
  return out;
};

const ofType = (type) => ({ properties: { type: { const: type } }, required: ['type'] });

export function buildSchema() {
  const types = [...new Set([...OTHER_TYPES, ...Object.keys(REQUIRED_FIELDS)])].sort();
  const perType = Object.entries(REQUIRED_FIELDS).map(([type, list]) => ({ if: ofType(type), then: needs(list) }));
  // A wellness encounter is scheduled by Synthea itself and needs no class or code.
  perType.push({
    if: { ...ofType('Encounter'), not: { required: ['wellness'], properties: { wellness: { const: true } } } },
    then: { required: ['encounter_class', 'codes'], properties: { codes: { type: 'array', minItems: 1 } } }
  });
  const target = { type: 'string', minLength: 1 };
  return {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $id: 'https://forschungsgruppe-digital-health.github.io/schema/synthea/module.schema.json',
    title: 'Synthea generic module',
    description:
      'Generated by tools/bpmn2gmf/gen-schema.mjs from required-fields.mjs; do not edit. Per-state structure only: ' +
      'reachability, existing transition targets and probability sums are checked by verify.mjs.',
    type: 'object',
    required: ['name', 'states'],
    properties: {
      name: { type: 'string', minLength: 1 },
      remarks: { type: 'array', items: { type: 'string' } },
      gmf_version: { type: 'integer' },
      specialty: { type: 'string' },
      states: {
        type: 'object',
        // The engine starts at the state named Initial; one shipped module (encounter/vitals) gives it another type.
        required: ['Initial'],
        additionalProperties: { $ref: '#/definitions/state' }
      }
    },
    definitions: {
      state: {
        type: 'object',
        required: ['type'],
        properties: {
          type: { enum: types },
          direct_transition: target,
          distributed_transition: { type: 'array', minItems: 1, items: { type: 'object', required: ['transition', 'distribution'], properties: { transition: target } } },
          conditional_transition: { type: 'array', minItems: 1, items: { type: 'object', required: ['transition'], properties: { transition: target } } },
          complex_transition: { type: 'array', minItems: 1 },
          lookup_table_transition: { type: 'array', minItems: 1 }
        },
        allOf: [
          // Terminal ends the module; every other state has exactly one transition.
          { if: ofType('Terminal'), then: { not: { anyOf: TRANSITIONS.map((t) => ({ required: [t] })) } }, else: { oneOf: TRANSITIONS.map((t) => ({ required: [t] })) } },
          ...perType
        ]
      }
    }
  };
}

export const render = () => `${JSON.stringify(buildSchema(), null, 2)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    let stored = '';
    try { stored = readFileSync(SCHEMA_PATH, 'utf8'); } catch { /* missing counts as stale */ }
    if (stored !== text) {
      console.error('module.schema.json is out of date: run `node tools/bpmn2gmf/gen-schema.mjs`.');
      process.exit(1);
    }
    console.log('module.schema.json is up to date.');
  } else {
    writeFileSync(SCHEMA_PATH, text);
    console.log(`wrote ${SCHEMA_PATH}`);
  }
}
