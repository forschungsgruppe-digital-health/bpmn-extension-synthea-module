#!/usr/bin/env node
// Usage: node tools/build-converter-site.mjs [<bpmn dir>] [--out-dir <dir>] [--fuse-gateways]
//
// Runs the bpmn2gmf converter on a pathway folder (default: lung-cancer/) and
// writes a small static site that a reviewer can open without a checkout:
//   <out>/index.html      links to every module and the report
//   <out>/report.txt      conversion report as text (errors, warnings, notes)
//   <out>/report.json     the same items as data
//   <out>/build.json      which commit the result was built from (GITHUB_SHA in the workflow, else git)
//   <out>/<module>.json   the generated Synthea modules (submodules in a subfolder)
//
// The Pages workflow calls it after the demo build with `--out-dir demo/dist/modules`.
// Exit code 1 if the conversion found errors, so a broken state is not published.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { convert } from './bpmn2gmf/convert.mjs';
import { writeModules } from './bpmn2gmf/write.mjs';
import { explain } from './bpmn2gmf/explanations.mjs';

const args = process.argv.slice(2);
let dir = 'lung-cancer';
let outDir = 'out/converter-site';
let fuse = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--out-dir') outDir = args[++i];
  else if (args[i] === '--fuse-gateways') fuse = true;
  else dir = args[i];
}

const git = (...a) => {
  try {
    return execFileSync('git', a, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
};
const build = {
  commit: process.env.GITHUB_SHA || git('rev-parse', 'HEAD') || 'unknown',
  ref: process.env.GITHUB_REF_NAME || git('branch', '--show-current') || 'unknown',
  repository: process.env.GITHUB_REPOSITORY || '',
  date: new Date().toISOString()
};

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.bpmn'))
  .sort()
  .map((f) => join(dir, f));
if (!files.length) {
  console.error(`no .bpmn files in ${dir}`);
  process.exit(2);
}

const { modules, diagnostics } = await convert(
  files.map((path) => ({ path, xml: readFileSync(path, 'utf8') })),
  { strict: true, fuse }
);

mkdirSync(outDir, { recursive: true });
const written = writeModules(modules, outDir);

const lines = diagnostics.format();
writeFileSync(join(outDir, 'report.txt'), `${lines.join('\n')}\n`);
writeFileSync(join(outDir, 'report.json'), `${JSON.stringify(diagnostics.items, null, 2)}\n`);

writeFileSync(join(outDir, 'build.json'), `${JSON.stringify(build, null, 2)}\n`);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const count = (level) => diagnostics.items.filter((i) => i.level === level).length;
const codes = [...new Set(diagnostics.items.map((i) => i.code))].filter((c) => explain(c));
const explained = codes
  .map((c) => {
    const e = explain(c);
    return `      <dt><code>${esc(c)}</code> (${diagnostics.items.filter((i) => i.code === c).length}x)</dt>\n      <dd>${esc(e.what)} ${esc(e.why)} <strong>What to do:</strong> ${esc(e.fix)}</dd>`;
  })
  .join('\n');
const short = build.commit.slice(0, 7);
const commitLink = build.repository && build.commit !== 'unknown'
  ? `<a href="https://github.com/${esc(build.repository)}/commit/${esc(build.commit)}"><code>${esc(short)}</code></a>`
  : `<code>${esc(short)}</code>`;
const failed = modules.filter((m) => !m.ok).map((m) => m.path);

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>Converter result — synthea</title>
    <style>
      body { font: 16px/1.5 system-ui, sans-serif; max-width: 52rem; margin: 2rem auto; padding: 0 1rem; }
      code, pre { font-family: ui-monospace, monospace; font-size: 0.9em; }
      dd { margin: 0 0 0.75rem; }
      pre { background: #f4f4f4; padding: 0.75rem; overflow-x: auto; }
      .error { color: #b00020; }
      @media (prefers-color-scheme: dark) { body { background: #161616; color: #e6e6e6; } pre { background: #232323; } a { color: #8ab4f8; } .error { color: #ff6b6b; } }
    </style>
  </head>
  <body>
    <p><a href="../">&larr; Back to the modeler</a></p>
    <h1>Converter result</h1>
    <p>Synthea modules generated by <code>tools/bpmn2gmf</code> from the BPMN models in <code>${esc(dir)}/</code>. The page is rebuilt on every merge into <code>dev</code>.</p>
    <p>Built from commit ${commitLink} on <code>${esc(build.ref)}</code>, ${esc(build.date.slice(0, 16).replace('T', ' '))} UTC.</p>
    <h2>Modules (${written.length})</h2>
    <ul>
${written.map((p) => `      <li><a href="${esc(p)}.json"><code>${esc(p)}.json</code></a></li>`).join('\n')}
    </ul>
${failed.length ? `    <p class="error">Not written because of errors: ${failed.map((p) => `<code>${esc(p)}</code>`).join(', ')}</p>\n` : ''}    <h2>Report</h2>
    <p>${count('error')} errors, ${count('warning')} warnings, ${count('note')} notes. Download: <a href="report.txt">report.txt</a>, <a href="report.json">report.json</a>.</p>
    ${codes.length ? `<h2>What the messages mean</h2>\n    <dl>\n${explained}\n    </dl>\n    ` : ''}<pre>${lines.length ? esc(lines.join('\n')) : 'No messages.'}</pre>
  </body>
</html>
`;
writeFileSync(join(outDir, 'index.html'), html);

console.log(`${written.length} module(s), ${count('error')} error(s), ${count('warning')} warning(s) -> ${outDir}`);
process.exit(diagnostics.errorCount ? 1 : 0);
