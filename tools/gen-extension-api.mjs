#!/usr/bin/env node
//
// Generates docs/extension-api-types.md, the reference of the `synthea:` types, attributes and
// enumerations, from the moddle descriptor (extension/model/synthea.json) and the fixed value
// lists next to it (synthea.values.json). The descriptor stays the only source, so the
// reference cannot drift: `--check` exits 1 when the file on disk is stale (runs in `validate`).
//
//   node tools/gen-extension-api.mjs           # write docs/extension-api-types.md
//   node tools/gen-extension-api.mjs --check   # exit 1 if it is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadValues } from './moddle-to-xsd.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const descriptorPath = `${root}extension/model/synthea.json`;
const outPath = `${root}docs/extension-api-types.md`;

const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);
const code = (s) => `\`${s}\``;
const list = (values) => values.map(code).join(', ');

/**
 * Builds the Markdown of the type reference.
 * @param {object} descriptor the moddle descriptor
 * @param {object} values the contents of the values file (`lists` and `xsd`), or {}
 * @returns {string} the Markdown, ending with a newline
 */
export function generateApiReference(descriptor, values = {}) {
  const { uri, prefix, version, types = [], xml = {} } = descriptor;
  const enums = types.filter((t) => t.isEnum);
  const enumByName = new Map(enums.map((e) => [e.name, e.literalValues.map((l) => l.name)]));
  const elements = types.filter((t) => !t.isEnum);
  const tag = (name) => (xml.tagAlias === 'lowerCase' ? lowerFirst(name) : name);
  const fixed = (typeName, prop) => {
    const listName = values.xsd?.[`${typeName}.${prop}`];
    return listName ? values.lists[listName] : undefined;
  };

  const out = [];
  out.push('# The `synthea:` types (reference)', '');
  out.push('<!-- Generated by `npm run api:gen` from extension/model/synthea.json and synthea.values.json. Do not edit. -->', '');
  out.push(
    `The data model of the extension: **${elements.length} types** and **${enums.length} enumerations** in the namespace ` +
      `${code(uri)} (prefix ${code(prefix)}, descriptor version ${version}). ` +
      'This page lists the data only. How to use the types is in the [modeling guide](modeling-guide.md) ' +
      'and in the [extension matrix](extension-matrix.md) (which type sits on which BPMN element); ' +
      'how to register the extension is in the [extension API](extension-api.md).',
    ''
  );
  out.push(
    `In the XML a type is written with a lower-case first letter: the type ${code('DelayConfig')} is the element ${code(`<${prefix}:${tag('DelayConfig')}>`)}. ` +
      'An attribute is always optional in the model; which ones a state needs is checked by the lint rules and the converter, not by the schema. ' +
      '"Allowed values" are the literals of an enumeration, or the fixed lists that the XSD enforces for a text field.',
    ''
  );

  out.push('## Types', '');
  out.push('| Type | XML element |', '|---|---|');
  for (const t of elements) out.push(`| [${code(t.name)}](#${t.name.toLowerCase()}) | ${code(`<${prefix}:${tag(t.name)}>`)} |`);
  out.push('');

  for (const t of elements) {
    out.push(`### ${t.name}`, '');
    out.push(`XML: ${code(`<${prefix}:${tag(t.name)}>`)}`, '');
    out.push('| Property | Kind | Type | Default | Allowed values |', '|---|---|---|---|---|');
    for (const p of t.properties ?? []) {
      const kind = p.isAttr ? 'attribute' : p.isMany ? 'child elements' : 'child element';
      const literals = enumByName.get(p.type);
      const fixedValues = fixed(t.name, p.name);
      const allowed = literals ? list(literals) : fixedValues ? list(fixedValues) : '';
      const type = enumByName.has(p.type) ? `[${p.type}](#${p.type.toLowerCase()})` : code(p.type);
      out.push(`| ${code(p.name)} | ${kind} | ${type} | ${p.default === undefined ? '' : code(p.default)} | ${allowed} |`);
    }
    out.push('');
  }

  out.push('## Enumerations', '');
  for (const e of enums) {
    out.push(`### ${e.name}`, '', list(e.literalValues.map((l) => l.name)), '');
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const descriptor = JSON.parse(readFileSync(descriptorPath, 'utf8'));
  const markdown = generateApiReference(descriptor, loadValues(descriptorPath));
  if (process.argv.includes('--check')) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (current !== markdown) {
      console.error('docs/extension-api-types.md is stale. Run `npm run api:gen` and commit the result.');
      process.exit(1);
    }
    console.log('docs/extension-api-types.md is up to date');
  } else {
    writeFileSync(outPath, markdown);
    console.log(`wrote ${outPath}`);
  }
}
